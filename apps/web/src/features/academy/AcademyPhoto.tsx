import Image from 'next/image';
import type { AcademyLocale } from './catalog-ui-v1-data';
import { getAcademyPhoto } from './academy-photo-v1';

export function AcademyPhoto({ locale, lawNumber, topicSlug }: {
  locale: AcademyLocale;
  lawNumber: number;
  topicSlug?: string;
}) {
  const photo = getAcademyPhoto(lawNumber, topicSlug);
  return <figure className="rv-academy__photo">
    <Image
      className="rv-academy__photo-image"
      src={photo.src}
      alt={photo.alt[locale]}
      width={1672}
      height={941}
      sizes="(max-width: 768px) 100vw, 900px"
    />
    <figcaption className="rv-academy__photo-caption">
      <span>{locale === 'es' ? 'Escena ilustrativa generada por RefView; no corresponde a un partido real.' : 'Illustrative scene generated by RefView; it does not depict a real match.'}</span>
      <span className="rv-academy__photo-observe">{photo.observe[locale]}</span>
    </figcaption>
  </figure>;
}
